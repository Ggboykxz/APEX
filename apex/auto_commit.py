"""Auto-commit after a one-shot task with a conventional commit message.

``apex -p "..." --auto-commit`` stages every change the agent made inside the
working directory and commits it. The message is generated by the same LLM
used for the task (one extra, cheap, tool-less call) and is sanitized to
conventional-commit shape:

    <type>(<scope>)?: <subject>   (subject lowercase-ish, <= 72 chars, no '.')

When the model is unavailable or returns garbage, a deterministic fallback
message is used so a task that succeeded is never lost to a commit failure.

Safety:

* only runs inside a git repository;
* only stages/commits the working directory (never other checkouts);
* never uses ``--force`` and never touches history (no rebase/amend);
* uncommitted work is never destroyed: if anything fails, the changes stay
  in the working tree and the error is reported.
"""

from __future__ import annotations

import logging
import re
import subprocess
from pathlib import Path
from typing import Any, Callable

__all__ = [
    "ALLOWED_TYPES",
    "MAX_SUBJECT_LENGTH",
    "sanitize_message",
    "is_git_repo",
    "has_changes",
    "generate_commit_message",
    "auto_commit",
]

logger = logging.getLogger(__name__)

ALLOWED_TYPES: tuple[str, ...] = (
    "feat",
    "fix",
    "docs",
    "style",
    "refactor",
    "perf",
    "test",
    "build",
    "ci",
    "chore",
)

MAX_SUBJECT_LENGTH = 72
_MAX_DIFFSTAT_CHARS = 2000
_MAX_DIFF_CHARS = 4000
_FALLBACK_MESSAGE = "chore: auto commit after apex task"

_MESSAGE_RE = re.compile(
    r"^(?P<type>" + "|".join(ALLOWED_TYPES) + r")"
    r"(?P<scope>\([a-z0-9._-]+\))?"
    r"(?P<bang>!)?:\s*(?P<subject>\S.*)$"
)

_LLM_PROMPT = (
    "You are a commit-message generator. Write exactly ONE conventional "
    "commit message for the working-tree changes below.\n"
    "Rules:\n"
    "- Format: type(scope): subject — scope optional.\n"
    "- type is one of: " + ", ".join(ALLOWED_TYPES) + ".\n"
    "- subject: imperative mood, at most 72 characters, no trailing period.\n"
    "- No body, no bullet points, no quotes, no explanation.\n\n"
    "Task that produced the changes: {task}\n\n"
    "Change summary (git diff --stat):\n{stat}\n\n"
    "Diff excerpt:\n{diff}\n\n"
    "Commit message:"
)


def _run_git(cwd: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", *args],
        cwd=str(cwd),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=60,
    )


def is_git_repo(cwd: Path | str) -> bool:
    """True when *cwd* is inside a git working tree."""
    try:
        result = _run_git(Path(cwd), "rev-parse", "--is-inside-work-tree")
    except (OSError, subprocess.SubprocessError):
        return False
    return result.returncode == 0 and result.stdout.strip() == "true"


def has_changes(cwd: Path | str) -> bool:
    """True when the working tree has staged or unstaged changes."""
    if not is_git_repo(cwd):
        return False
    result = _run_git(Path(cwd), "status", "--porcelain")
    return result.returncode == 0 and bool(result.stdout.strip())


def sanitize_message(raw: str | None) -> str | None:
    """Normalize model output to a valid conventional message, or None."""
    if not raw:
        return None
    # First non-empty line only; strip wrapping quotes and backticks.
    for line in raw.replace("\r", "\n").split("\n"):
        line = line.strip().strip('"').strip("`").strip()
        if not line:
            continue
        # Drop a leading "commit message" style prefix if the model added one.
        line = re.sub(r"^(commit message|message)\s*[:\-]\s*", "", line, flags=re.IGNORECASE)
        # Normalize the whole header: lowercase the type part.
        candidate = line
        match = _MESSAGE_RE.match(candidate)
        if match:
            subject = " ".join(match.group("subject").split())
            subject = re.sub(r"[.!]+$", "", subject)
            if len(subject) > MAX_SUBJECT_LENGTH:
                cut = subject[: MAX_SUBJECT_LENGTH - 1].rstrip()
                subject = f"{cut}…"
            candidate = (
                f"{match.group('type').lower()}{match.group('scope') or ''}"
                f"{match.group('bang') or ''}: {subject}"
            )
        if _MESSAGE_RE.match(candidate):
            return candidate
        return None
    return None


def _collect_diff(cwd: Path) -> tuple[str, str]:
    stat = _run_git(cwd, "diff", "--stat", "HEAD").stdout or ""
    diff = _run_git(cwd, "diff", "HEAD").stdout or ""
    # Untracked files are not in `diff`; list them so the model knows about them.
    untracked = _run_git(cwd, "ls-files", "--others", "--exclude-standard").stdout or ""
    stat = stat[:_MAX_DIFFSTAT_CHARS]
    diff = diff[:_MAX_DIFF_CHARS]
    return stat or "(no diff for tracked files)", (diff + ("\n" + untracked if untracked else ""))[
        :_MAX_DIFF_CHARS
    ]


def generate_commit_message(
    cwd: Path | str,
    task: str = "",
    llm: Callable[[str], str] | None = None,
) -> str:
    """Generate a conventional commit message for the working tree changes.

    *llm* is a zero-setup seam for tests: a callable taking the full prompt
    and returning raw model text. When omitted, a single litellm call is made
    without tools. Any failure degrades to :data:`_FALLBACK_MESSAGE`.
    """
    cwd = Path(cwd)
    try:
        stat, diff = _collect_diff(cwd)
        prompt = _LLM_PROMPT.format(task=task or "(no task description)", stat=stat, diff=diff)
        if llm is None:
            import litellm

            llm = lambda p: (  # noqa: E731 - small local closure
                litellm.completion(
                    model="gpt-4o-mini",
                    messages=[{"role": "user", "content": p}],
                    max_tokens=64,
                    timeout=30,
                )
                .choices[0]
                .message.content
                or ""
            )
        raw = llm(prompt)
    except Exception as exc:  # noqa: BLE001 - any LLM failure must not lose the task
        logger.info("auto-commit message generation failed, using fallback: %s", exc)
        return _FALLBACK_MESSAGE
    return sanitize_message(raw) or _FALLBACK_MESSAGE


def auto_commit(
    cwd: Path | str,
    task: str = "",
    llm: Callable[[str], str] | None = None,
) -> dict[str, Any]:
    """Stage and commit the working-tree changes in *cwd*.

    Returns a dict with ``status`` of ``committed``, ``no-changes``,
    ``not-a-repo`` or ``error`` (plus ``sha``/``message`` when committed).
    Never raises: a failure here must not turn a successful task into a crash.
    """
    cwd = Path(cwd).expanduser()
    if not is_git_repo(cwd):
        return {"status": "not-a-repo", "cwd": str(cwd)}
    if not has_changes(cwd):
        return {"status": "no-changes", "cwd": str(cwd)}

    message = generate_commit_message(cwd, task=task, llm=llm)

    try:
        add = _run_git(cwd, "add", "-A")
        if add.returncode != 0:
            return {
                "status": "error",
                "cwd": str(cwd),
                "error": f"git add failed: {add.stderr.strip()}",
            }
        commit = _run_git(cwd, "commit", "-m", message)
        if commit.returncode != 0:
            # Roll the index back so the tree is left exactly as found.
            _run_git(cwd, "reset", "HEAD")
            return {
                "status": "error",
                "cwd": str(cwd),
                "error": f"git commit failed: {commit.stderr.strip()}",
                "message": message,
            }
        sha = _run_git(cwd, "rev-parse", "HEAD").stdout.strip()
        return {"status": "committed", "cwd": str(cwd), "sha": sha, "message": message}
    except (OSError, subprocess.SubprocessError) as exc:
        return {"status": "error", "cwd": str(cwd), "error": str(exc)}


if __name__ == "__main__":  # pragma: no cover
    import json
    import sys

    print(json.dumps(auto_commit(Path.cwd() if not sys.argv[1:] else Path(sys.argv[1]))))
